    def _build_menu_bar(self):
        bar=ttk.Frame(self.toolbar,padding=(0,0))
        bar.grid(row=0,column=0,sticky="ew")
        def menu(title,existing=None):
            control=ttk.Menubutton(bar,text=title,style="AppMenu.TMenubutton",width=0)
            control.pack(side="left",padx=(0,8))
            value=existing or tk.Menu(control,tearoff=False,bg="#1c222c",fg="#e7ecf4",activebackground="#34445a",activeforeground="white")
            value.configure(font=("Segoe UI",11))
            control.configure(menu=value)
            self._tooltip(control,title+" menu (Alt+"+title[0]+")")
            self.root.bind("<Alt-"+title[0].lower()+">",lambda event,control=control,value=value:value.tk_popup(control.winfo_rootx(),control.winfo_rooty()+control.winfo_height()))
            return value
        file=menu("File")
        self.file_menu=file
        for label,command,shortcut in (("Open folder…",self._choose_folder,"Ctrl+O"),("Rescan",self._scan,"S"),("Cancel scan",self._cancel,""),("Copy recommended photos…",self._copy_ranked,""),("Open in editor",self._open_current,""),("Export report…",self._export,"")):
            file.add_command(label=label,command=command,accelerator=shortcut)
        file.add_separator();file.add_command(label="Exit",command=self._close)
        edit=menu("Edit")
        edit.add_command(label="Toggle favourite",command=self._toggle_favourite,accelerator="P")
        edit.add_command(label="Lock / unlock review choices",command=self._toggle_lock,accelerator="L")
